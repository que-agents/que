// Writes docs/cli.md from the CLI's own `--help` output, so the reference
// cannot drift from the commands. Run after `npm run build:node`:
//
//   node scripts/cli-reference.mjs           write docs/cli.md
//   node scripts/cli-reference.mjs --check   exit 1 if docs/cli.md is stale
import { execFileSync } from 'node:child_process'
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import os from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const cli = join(root, 'out/cli/index.js')
const target = join(root, 'docs/cli.md')
// Help never touches QUE_HOME, but never point anything at the real one.
const home = mkdtempSync(join(os.tmpdir(), 'que-cli-ref-'))
process.on('exit', () => rmSync(home, { recursive: true, force: true }))
if (!existsSync(cli)) {
  console.error('out/cli/index.js is missing; run npm run build:node first')
  process.exit(1)
}

function help(path) {
  // `que <parent> help <name>` rather than `--help`: `que hook` reads stdin
  // before commander sees its arguments.
  const argv =
    path.length === 0 ? ['--help'] : [...path.slice(0, -1), 'help', path[path.length - 1]]
  return execFileSync(process.execPath, [cli, ...argv], {
    encoding: 'utf8',
    // A fixed width, so the output is the same on every machine.
    env: { ...process.env, COLUMNS: '100', QUE_HOME: home }
  })
}

/** The entries of one help section ("Commands:", "Options:"), joining wrapped lines. */
function section(text, title) {
  const lines = text.split('\n')
  const start = lines.indexOf(`${title}:`)
  if (start < 0) return []
  const entries = []
  for (const line of lines.slice(start + 1)) {
    if (line.trim() === '') break
    if (/^ {2}\S/.test(line)) {
      const m = /^ {2}(\S.*?)(?: {2,}(.*))?$/.exec(line)
      entries.push({ term: m[1].trim(), desc: (m[2] ?? '').trim() })
    } else if (entries.length > 0) {
      const last = entries[entries.length - 1]
      last.desc = `${last.desc} ${line.trim()}`.trim()
    }
  }
  return entries
}

/** Every leaf command, depth first, with its help text. */
function walk(path, out) {
  const text = help(path)
  const subs = section(text, 'Commands').filter((c) => !c.term.startsWith('help '))
  if (path.length > 0) out.push({ path, text, hasSubs: subs.length > 0 })
  for (const c of subs) walk([...path, c.term.split(' ')[0]], out)
  return out
}

const top = help([])
const version = /^Usage: que/m.test(top)
  ? execFileSync(process.execPath, [cli, '--version'], { encoding: 'utf8' }).trim()
  : ''
const all = walk([], [])
const summary = (cmd) => {
  const parent = all.find((c) => c.path.join(' ') === cmd.path.slice(0, -1).join(' '))
  const list = section(parent ? parent.text : top, 'Commands')
  return list.find((e) => e.term.split(' ')[0] === cmd.path[cmd.path.length - 1])
}

let table = '| Command | What it does |\n| ------- | ------------ |\n'
for (const cmd of all) {
  if (cmd.hasSubs) continue
  const s = summary(cmd)
  const usage = /^Usage: (.*)$/m.exec(cmd.text)?.[1] ?? `que ${cmd.path.join(' ')}`
  table += `| \`${usage.replace(/\|/g, '\\|')}\` | ${(s?.desc ?? '').replace(/\|/g, '\\|')} |\n`
}

let md = `# que CLI reference

Generated by \`scripts/cli-reference.mjs\` from \`que --help\` (que ${version}). Do not edit by
hand; run \`npm run docs\` after changing a command.

${table}`
md += '\n## Details\n'
for (const cmd of all) {
  if (cmd.hasSubs) continue
  md += `\n### que ${cmd.path.join(' ')}\n\n\`\`\`text\n${cmd.text.trim()}\n\`\`\`\n`
}

// The same table in the README, between its generated markers.
const readmePath = join(root, 'README.md')
const readme = readFileSync(readmePath, 'utf8')
const re = /(<!-- generated:cli-table -->\n)[\s\S]*?(<!-- \/generated -->)/
if (!re.test(readme)) throw new Error('README.md has no generated:cli-table block')
const nextReadme = readme.replace(re, `$1${table}$2`)

if (process.argv.includes('--check')) {
  const current = existsSync(target) ? readFileSync(target, 'utf8') : ''
  if (current !== md || readme !== nextReadme) {
    console.error('docs/cli.md or the README CLI table is stale; run npm run docs')
    process.exit(1)
  }
  console.log('docs/cli.md and the README CLI table are up to date')
} else {
  writeFileSync(target, md)
  writeFileSync(readmePath, nextReadme)
  console.log(`wrote ${target} (${all.filter((c) => !c.hasSubs).length} commands)`)
}
